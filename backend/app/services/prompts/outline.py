"""大纲生成提示词与内置范本。

提示词来自 PRD V2.2 第四节「大纲生成」；范本为发改委 2023 年版
《企业投资项目可行性研究报告编写参考大纲》十章（程序内置，不进资料库）。
"""
from __future__ import annotations

# 发改委 2023 年版《企业投资项目可行性研究报告编写参考大纲》十章（内置范本）
OUTLINE_TEMPLATE = """一、概述
（项目概况、建设单位、建设地点、建设内容与规模、建设工期、投资估算、主要技术经济指标）

二、项目建设背景和必要性
（政策背景、行业发展现状、市场/需求分析、项目建设必要性）

三、项目需求分析与产出方案
（需求分析、建设内容和规模、产出方案、建设标准）

四、项目选址与要素保障
（选址条件、建设条件、土地/能源/人力等要素保障）

五、项目建设方案
（技术方案、设备方案、工程方案、建设管理）

六、项目运营方案
（运营模式、运营组织、安全与应急、绩效管理）

七、项目投融资与财务方案
（投资估算、融资方案、财务分析：成本/收入/盈利能力/偿债能力）

八、项目影响效果分析
（经济影响、社会影响、生态环境影响、资源能源利用）

九、项目风险管控方案
（风险识别、风险管控措施）

十、研究结论及建议
（研究结论、主要建议）"""


def build_outline_prompt(
    *,
    title: str,
    target_words: int,
    user_requirements: str | None,
) -> str:
    domain = "氢能"
    style = "正式"
    extra = user_requirements.strip() if user_requirements else "（无）"
    return f"""# Role
你是一名拥有15年经验的能源行业高级咨询顾问，专门负责氢能项目可行性研究报告的架构设计。

# Inputs
报告标题：{title}
内容领域：{domain}
文档风格：{style}
目标总字数：{target_words}
额外要求：{extra}
编写大纲范本（发改委 2023 年版企业投资项目可研报告编写参考大纲，程序内置全文）：{OUTLINE_TEMPLATE}

# Action Path
1. 以编写大纲范本为准，结合氢能项目特点调整章节结构。
2. 每章写 2 到 3 个关键论点，列出本章要用到的关键数据名称。
3. 按目标总字数给每章分配建议字数。

# Output
只输出 JSON，不要任何开场白：
{{"full_outline": [{{"chapter_id": 1, "title": "章节名称", "key_points": ["论点1", "论点2"], "data_needed": ["总投资"], "suggested_words": 1200}}]}}

# Constraints
- 一级章节 8 到 13 个，逻辑从"为什么做"到"怎么做"再到"收益如何"。
- data_needed 只写数据名称，不写数值。数值一律由正文从 truth_base 取。
- 章节标题专业、干练，不用"关于……"这类前缀。
- 禁止输出任何 JSON 之外的文字。"""
